// FAQPage structured data. Only pass questions that are visibly rendered on the same page.
// Valid markup does not guarantee a Google rich result; it only describes the visible content.
export function faqJsonLd(items: readonly { question: string; answer: string }[]) {
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: items.map((item) => ({
      "@type": "Question",
      name: item.question,
      acceptedAnswer: { "@type": "Answer", text: item.answer },
    })),
  };
}
