// Drafts exist only for `next dev` preview. Production (build and runtime) sees approved pages only.
export function isPreviewEnabled(): boolean {
  return process.env.NODE_ENV === "development";
}

export function isProblemVisible(problem: ProblemPage): boolean {
  return problem.status === "approved" || isPreviewEnabled();
}

export function getApprovedProblemPages(): readonly ProblemPage[] {
  return problemPages.filter((problem) => problem.status === "approved");
}

// Pages that the current environment may serve: approved ones, plus drafts in development.
export function getVisibleProblemPages(): readonly ProblemPage[] {
  return problemPages.filter(isProblemVisible);
}

export function getProblemPage(serviceId: ApplianceId, slug: string): ProblemPage | undefined {
  return problemPages.find((problem) => problem.serviceId === serviceId && problem.slug === slug);
}

export function problemPath(problem: ProblemPage): string {
  const service = getServiceById(problem.serviceId);
  if (!service) throw new Error(`Problem page "${problem.slug}" points to an unknown service "${problem.serviceId}".`);
  return `${servicePath(service)}/${problem.slug}`;
}

// Public links (cards, related links) go to approved pages only, never to drafts, even in development.
export function getApprovedProblemForCard(serviceId: ApplianceId, cardTitle: string): ProblemPage | undefined {
  return getApprovedProblemPages().find((problem) => problem.serviceId === serviceId && problem.cardTitle === cardTitle);
}

// A code row links to a guide only when the guide's reference matches the stored row (brand + code, and the stored
// model when the reference is limited to one model).
export function getApprovedProblemsForCode(
  category: string,
  brand: string,
  errorCode: string,
  model: string | null,
): ProblemPage[] {
  return getApprovedProblemPages().filter(
    (problem) =>
      problem.serviceId === category &&
      problem.codeRefs.some(
        (ref) => ref.brand === brand && ref.code === errorCode && (ref.model === undefined || ref.model === model),
      ),
  );
}

export function getSiblingApprovedProblems(problem: ProblemPage): ProblemPage[] {
  return getApprovedProblemPages().filter((item) => item.serviceId === problem.serviceId && item.slug !== problem.slug);
}
