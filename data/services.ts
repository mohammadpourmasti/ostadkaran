export function getServiceBySlug(slug: string): Service | undefined {
  return services.find((service) => service.slug === slug);
}

export function getServiceById(id: ApplianceId): Service | undefined {
  return services.find((service) => service.id === id);
}

export function servicePath(service: Service): string {
  return `/services/${service.slug}`;
}

// Uses the existing /repair-request?appliance=<ApplianceId> convention (the id, never the slug).
export function repairRequestHref(service: Service): string {
  return `${siteConfig.links.repairRequest}?appliance=${service.id}`;
}
